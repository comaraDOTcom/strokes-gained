/**
 * Drizzle schema (Postgres — Neon in production, PGlite locally and in tests).
 *
 * Canonical storage unit is YARDS (`double precision`) for every lie, including
 * GREEN. Feet<->yards conversion happens in exactly one place: `src/lib/units.ts`
 * (feet on write for GREEN, yards->feet on display). Nothing else in the app
 * should do that arithmetic inline. NOTE: every float here is `doublePrecision`,
 * never `real` — pg `real` is 4-byte and would corrupt fractional-yard green
 * distances and the 3-decimal SG values the tests assert.
 *
 * `sg` / `category` / `baseline_id` on `shots` are DERIVED, denormalised
 * columns — always produced by `recomputeRound()` (see
 * `src/lib/sg/recompute.ts`), never written directly by a form. Hole score
 * is likewise always derived from `shots`, never stored as its own input.
 *
 * Ids are `generated by default` (not `always`) so `scripts/migrate-sqlite-to-pg.ts`
 * can carry the original SQLite ids across.
 *
 * Ownership: `rounds.user_id` and `courses.created_by_user_id` point at the Better
 * Auth `user` table. Both are NULLABLE on purpose — rows imported from the
 * single-user SQLite era have no owner until the admin first signs in, at which
 * point `claimLegacyData()` (src/lib/auth/claim.ts) assigns them.
 */
import {
  pgTable,
  text,
  integer,
  doublePrecision,
  boolean,
  timestamp,
  uniqueIndex,
  index,
  primaryKey,
} from 'drizzle-orm/pg-core';

// ---------------------------------------------------------------------------
// Auth (Better Auth core tables — names/shape per its Drizzle adapter)
// ---------------------------------------------------------------------------

export const user = pgTable('user', {
  id: text('id').primaryKey(),
  name: text('name').notNull(),
  email: text('email').notNull().unique(),
  emailVerified: boolean('email_verified').notNull().default(false),
  image: text('image'),
  createdAt: timestamp('created_at').notNull().defaultNow(),
  updatedAt: timestamp('updated_at').notNull().defaultNow(),
});

export const session = pgTable(
  'session',
  {
    id: text('id').primaryKey(),
    expiresAt: timestamp('expires_at').notNull(),
    token: text('token').notNull().unique(),
    createdAt: timestamp('created_at').notNull().defaultNow(),
    updatedAt: timestamp('updated_at').notNull().defaultNow(),
    ipAddress: text('ip_address'),
    userAgent: text('user_agent'),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
  },
  (t) => ({ userIdx: index('session_user_id_idx').on(t.userId) }),
);

export const account = pgTable(
  'account',
  {
    id: text('id').primaryKey(),
    accountId: text('account_id').notNull(),
    providerId: text('provider_id').notNull(),
    userId: text('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    accessToken: text('access_token'),
    refreshToken: text('refresh_token'),
    idToken: text('id_token'),
    accessTokenExpiresAt: timestamp('access_token_expires_at'),
    refreshTokenExpiresAt: timestamp('refresh_token_expires_at'),
    scope: text('scope'),
    password: text('password'),
    createdAt: timestamp('created_at').notNull().defaultNow(),
    updatedAt: timestamp('updated_at').notNull().defaultNow(),
  },
  (t) => ({ userIdx: index('account_user_id_idx').on(t.userId) }),
);

export const verification = pgTable(
  'verification',
  {
    id: text('id').primaryKey(),
    identifier: text('identifier').notNull(),
    value: text('value').notNull(),
    expiresAt: timestamp('expires_at').notNull(),
    createdAt: timestamp('created_at').notNull().defaultNow(),
    updatedAt: timestamp('updated_at').notNull().defaultNow(),
  },
  (t) => ({ identifierIdx: index('verification_identifier_idx').on(t.identifier) }),
);

// ---------------------------------------------------------------------------
// Golf data
